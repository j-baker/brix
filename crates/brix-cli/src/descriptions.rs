/// A `nix.conf` setting exposed as a flag.
pub fn setting(name: &str) -> String {
    if let Some(rest) = name.strip_prefix("no-") {
        return format!("Disable the `{rest}` setting.");
    }
    if let Some(rest) = name.strip_prefix("extra-") {
        return format!("Append to the `{rest}` setting.");
    }
    format!("Set the `{name}` setting.")
}
